import { prisma } from "../../lib/prisma";
import { AppError } from "../../lib/errors";
import { hashPassword } from "../../services/auth.service";
import { seedTenantRoles } from "../rbac/rbac.service";
import { addDays, addMonths, addYears } from "../../utils/dates";
import { OnboardingInput } from "./onboarding.validator";
import { recordAudit } from "../../services/audit.service";
import { Request } from "express";

const DEFAULT_LEAVE_TYPES = [
  { name: "Casual Leave", code: "CASUAL", quota: 10, paid: true },
  { name: "Sick Leave", code: "SICK", quota: 10, paid: true },
  { name: "Annual Leave", code: "ANNUAL", quota: 20, paid: true },
  { name: "Unpaid Leave", code: "UNPAID", quota: 0, paid: false },
];

function slugify(input: string): string {
  const base = input
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return base || `institution-${Date.now()}`;
}

async function uniqueSlug(name: string): Promise<string> {
  const base = slugify(name);
  let slug = base;
  let suffix = 2;
  while (await prisma.tenant.findUnique({ where: { slug } })) {
    slug = `${base}-${suffix++}`;
  }
  return slug;
}

/**
 * Full onboarding flow. Creates the tenant, admin user, default roles,
 * default branch, payroll/attendance/leave settings, payroll cycle, leave
 * types, and a trial (or active) subscription — all in a single transaction.
 */
export async function registerInstitution(input: OnboardingInput, req: Request) {
  const existingUser = await prisma.user.findUnique({ where: { email: input.email.toLowerCase().trim() } });
  if (existingUser) {
    throw AppError.conflict("An account with this email already exists.");
  }

  const plan = await prisma.subscriptionPlan.findUnique({
    where: { key: input.planKey },
    include: { features: true },
  });
  if (!plan || !plan.isActive) {
    throw AppError.badRequest("The selected plan is not available.", "PLAN_NOT_FOUND");
  }

  const slug = await uniqueSlug(input.institutionName);
  const passwordHash = await hashPassword(input.password);
  const now = new Date();
  const periodEnd = input.trial
    ? addDays(now, plan.trialDays)
    : input.billingPeriod === "YEARLY"
      ? addYears(now, 1)
      : addMonths(now, 1);
  const amount = input.billingPeriod === "YEARLY" ? plan.yearlyPrice : plan.monthlyPrice;

  const result = await prisma.$transaction(async (tx) => {
    const tenant = await tx.tenant.create({
      data: {
        name: input.institutionName,
        slug,
        institutionType: input.institutionType,
        email: input.institutionEmail || null,
        phone: input.phone,
        website: input.website,
        address: input.address,
        country: input.country,
        city: input.city,
        currency: input.currency,
        status: input.trial ? "TRIALING" : "ACTIVE",
      },
    });

    const user = await tx.user.create({
      data: {
        tenantId: tenant.id,
        email: input.email.toLowerCase().trim(),
        fullName: input.fullName,
        passwordHash,
        status: "ACTIVE",
      },
    });

    // Default branch
    await tx.branch.create({
      data: { tenantId: tenant.id, name: "Main Campus", code: "MAIN" },
    });

    // Default payroll/attendance/leave settings
    await tx.tenantSetting.createMany({
      data: [
        {
          tenantId: tenant.id,
          key: "payroll",
          value: { overtimeEnabled: false, approvalFlow: "single", workingDaysMethod: "ACTUAL_DAYS", workingDaysPerMonth: 22 },
        },
        {
          tenantId: tenant.id,
          key: "attendance",
          value: { workFromHomeEnabled: false, lateThresholdMinutes: 15, autoHolidayRecognition: true },
        },
        {
          tenantId: tenant.id,
          key: "leave",
          value: { autoUpdateAttendance: true, autoApplyInPayroll: true },
        },
      ],
    });

    // Default payroll cycle
    await tx.payrollCycle.create({
      data: {
        tenantId: tenant.id,
        name: "Monthly Payroll",
        type: "MONTHLY",
        payDay: 1,
        autoGenerateDay: 28,
        workingDaysMethod: "ACTUAL_DAYS",
        workingDaysPerMonth: 22,
        approvalFlow: { levels: [{ name: "HR Review" }, { name: "Accounts Approval" }] },
      },
    });

    // Default leave types
    for (const lt of DEFAULT_LEAVE_TYPES) {
      await tx.leaveType.create({
        data: {
          tenantId: tenant.id,
          name: lt.name,
          code: lt.code,
          annualQuota: lt.quota,
          isPaid: lt.paid,
          approvalRequired: true,
        },
      });
    }

    // Subscription (trial or active)
    const subscription = await tx.subscription.create({
      data: {
        tenantId: tenant.id,
        planId: plan.id,
        status: input.trial ? "TRIALING" : "ACTIVE",
        billingPeriod: input.billingPeriod,
        startDate: now,
        trialEndDate: input.trial ? periodEnd : null,
        currentPeriodStart: now,
        currentPeriodEnd: periodEnd,
        renewalDate: periodEnd,
        amount,
        currency: input.currency,
        autoRenew: true,
        paymentProvider: "MANUAL",
      },
    });

    return { tenant, user, subscription };
  });

  // Assign roles + permissions outside the interactive transaction
  await seedTenantRoles(result.tenant.id);
  const ownerRole = await prisma.role.findUnique({
    where: { tenantId_key: { tenantId: result.tenant.id, key: "owner" } },
  });
  if (ownerRole) {
    await prisma.userRole.create({ data: { userId: result.user.id, roleId: ownerRole.id } });
  }

  // Audit trail (platform-level: onboarding)
  await recordAudit({
    req,
    action: "tenant.registered",
    module: "onboarding",
    recordId: result.tenant.id,
    recordType: "Tenant",
    metadata: { plan: plan.key, trial: input.trial, email: result.user.email },
  });

  return result;
}
