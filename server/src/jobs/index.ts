import { Queue, Worker } from "bullmq";
import { env } from "../config/env";
import { logger } from "../config/logger";
import { processSubscriptionExpiry, sendExpiryReminders } from "../modules/subscriptions/subscriptions.service";
import { prisma } from "../lib/prisma";
import { dayjs } from "../utils/dates";

const connection = {
  url: env.REDIS_URL,
  // Heroku Redis serves TLS (rediss://) with a self-signed cert.
  ...(env.REDIS_URL.startsWith("rediss://") ? { tls: { rejectUnauthorized: false } } : {}),
};

// Queue names
export const QUEUES = {
  SUBSCRIPTION: "subscription-jobs",
  PAYROLL: "payroll-jobs",
  NOTIFICATION: "notification-jobs",
  GENERAL: "general-jobs",
} as const;

export const queues: Record<string, Queue> = {};

function createQueue(name: string): Queue | null {
  try {
    const queue = new Queue(name, { connection });
    queues[name] = queue;
    return queue;
  } catch (err) {
    logger.warn({ err, name }, "Failed to create queue");
    return null;
  }
}

export function logJobRun(jobName: string, queueName: string, jobId?: string, status = "RUNNING", metadata?: object) {
  return prisma.backgroundJobLog
    .create({ data: { jobName, queueName, jobId, status, metadata: metadata as object } })
    .catch(() => undefined);
}

// ---- Job handlers (also exported for direct/manual invocation) -------------

export async function handleSubscriptionExpiry() {
  const log = await logJobRun("subscription.check-expiry", QUEUES.SUBSCRIPTION);
  try {
    const changed = await processSubscriptionExpiry();
    await prisma.backgroundJobLog.update({ where: { id: log?.id }, data: { status: "COMPLETED", finishedAt: new Date() } }).catch(() => undefined);
    return changed;
  } catch (err) {
    await prisma.backgroundJobLog.update({ where: { id: log?.id }, data: { status: "FAILED", error: String(err), finishedAt: new Date() } }).catch(() => undefined);
    throw err;
  }
}

export async function handleExpiryReminders() {
  const log = await logJobRun("subscription.send-reminders", QUEUES.NOTIFICATION);
  try {
    const sent = await sendExpiryReminders();
    await prisma.backgroundJobLog.update({ where: { id: log?.id }, data: { status: "COMPLETED", finishedAt: new Date() } }).catch(() => undefined);
    return sent;
  } catch (err) {
    await prisma.backgroundJobLog.update({ where: { id: log?.id }, data: { status: "FAILED", error: String(err), finishedAt: new Date() } }).catch(() => undefined);
    throw err;
  }
}

export async function handleAutoPayrollGeneration() {
  const log = await logJobRun("payroll.auto-generate", QUEUES.PAYROLL);
  const today = dayjs().date();
  const cycles = await prisma.payrollCycle.findMany({ where: { isActive: true, autoGenerateDay: today } });
  let generated = 0;
  for (const cycle of cycles) {
    // Only auto-generate if a run for the current period doesn't exist.
    const periodStart = dayjs().startOf("month").toDate();
    const periodEnd = dayjs().endOf("month").toDate();
    const existing = await prisma.payrollRun.findFirst({
      where: { tenantId: cycle.tenantId, periodStart, periodEnd, status: { notIn: ["CANCELLED"] } },
    });
    if (existing) continue;
    generated++;
    // Auto-generation is enqueued per tenant to keep heavy work out of this pass.
    queues[QUEUES.PAYROLL]?.add("payroll.generate-for-tenant", { tenantId: cycle.tenantId, cycleId: cycle.id });
  }
  await prisma.backgroundJobLog.update({ where: { id: log?.id }, data: { status: "COMPLETED", finishedAt: new Date() } }).catch(() => undefined);
  return generated;
}

// ---- Startup ---------------------------------------------------------------

export function startWorkers(): void {
  try {
    const subscriptionQueue = createQueue(QUEUES.SUBSCRIPTION);
    const notificationQueue = createQueue(QUEUES.NOTIFICATION);
    const payrollQueue = createQueue(QUEUES.PAYROLL);
    createQueue(QUEUES.GENERAL);

    if (subscriptionQueue) {
      const worker = new Worker(
        QUEUES.SUBSCRIPTION,
        async (job) => {
          if (job.name === "subscription.check-expiry") return handleSubscriptionExpiry();
          if (job.name === "subscription.send-reminders") return handleExpiryReminders();
        },
        { connection },
      );
      worker.on("failed", (job, err) => logger.error({ err, jobId: job?.id }, "Subscription job failed"));
    }

    if (notificationQueue) {
      const worker = new Worker(
        QUEUES.NOTIFICATION,
        async (job) => {
          if (job.name === "subscription.send-reminders") return handleExpiryReminders();
        },
        { connection },
      );
      worker.on("failed", (job, err) => logger.error({ err, jobId: job?.id }, "Notification job failed"));
    }

    if (payrollQueue) {
      const worker = new Worker(
        QUEUES.PAYROLL,
        async (job) => {
          if (job.name === "payroll.auto-generate") return handleAutoPayrollGeneration();
        },
        { connection },
      );
      worker.on("failed", (job, err) => logger.error({ err, jobId: job?.id }, "Payroll job failed"));
    }

    logger.info("BullMQ workers started");
  } catch (err) {
    logger.warn({ err }, "Failed to start BullMQ workers (Redis unavailable?)");
  }
}

export function startSchedulers(): void {
  try {
    const subscriptionQueue = queues[QUEUES.SUBSCRIPTION];
    const notificationQueue = queues[QUEUES.NOTIFICATION];
    const payrollQueue = queues[QUEUES.PAYROLL];
    if (!subscriptionQueue || !notificationQueue || !payrollQueue) return;

    // Daily subscription expiry check at 00:05 UTC.
    subscriptionQueue.add(
      "subscription.check-expiry",
      {},
      { repeat: { pattern: "5 0 * * *" }, jobId: "repeat:subscription.check-expiry" },
    ).catch(() => undefined);

    // Hourly expiry reminders.
    notificationQueue.add(
      "subscription.send-reminders",
      {},
      { repeat: { every: 60 * 60 * 1000 }, jobId: "repeat:subscription.send-reminders" },
    ).catch(() => undefined);

    // Daily payroll auto-generation at 00:30 UTC.
    payrollQueue.add(
      "payroll.auto-generate",
      {},
      { repeat: { pattern: "30 0 * * *" }, jobId: "repeat:payroll.auto-generate" },
    ).catch(() => undefined);

    logger.info("BullMQ repeatable jobs scheduled");
  } catch (err) {
    logger.warn({ err }, "Failed to schedule repeatable jobs");
  }
}
